export function initI18n() {
  const header = document.querySelector<HTMLElement>('.masthead')!;
  const control = document.createElement('button');
  control.className = 'language-toggle';
  control.type = 'button';
  header.insertBefore(control, header.querySelector('.github-link'));
  let language = localStorage.getItem('chasheo-language') === 'en' ? 'en' : 'zh';
  const original = new WeakMap<Text, string>();
  const reverse = new Map(Object.entries(translations).map(([zh, en]) => [en, zh]));
  function dynamicTranslation(source: string) {
    let match = source.match(/^请在 (\d+) 秒内确认入场$/);
    if (match) return 'Please confirm within ' + match[1] + ' seconds';
    match = source.match(/^(\d+) 位访客正在等候$/);
    if (match) return match[1] + ' visitors waiting';
    return undefined;
  }
  function translate(node: Text) {
    if (node.parentElement?.closest('#comments-list, textarea, input, script, style')) return;
    const text = node.data;
    const trimmed = text.trim();
    const suffix = trimmed.match(/\s*[↗↙↻×✓↓↑]+$/)?.[0] || '';
    const label = suffix ? trimmed.slice(0, -suffix.length).trimEnd() : trimmed;
    const saved = original.get(node);
    const savedEnglish = saved && (translations[saved.trim()] || dynamicTranslation(saved.trim()));
    const source = saved && savedEnglish === label ? saved.trim() : (reverse.get(label) || label);
    const english = translations[source] || dynamicTranslation(source);
    if (!english) return;
    original.set(node, source);
    const result = (language === 'en' ? english : source) + suffix;
    if (trimmed !== result) node.data = text.replace(trimmed, result);
  }
  function walk(root: Node) {
    if (root.nodeType === Node.TEXT_NODE) { translate(root as Text); return; }
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    while (walker.nextNode()) translate(walker.currentNode as Text);
  }
  function apply() {
    document.documentElement.lang = language === 'zh' ? 'zh-CN' : 'en';
    control.textContent = language === 'zh' ? '中文 / EN' : 'EN / 中文';
    control.setAttribute('aria-label', language === 'zh' ? 'Switch to English' : '切换到中文');
    const name = document.querySelector<HTMLInputElement>('#comment-name');
    const message = document.querySelector<HTMLTextAreaElement>('#comment-body');
    if (name) name.placeholder = language === 'zh' ? '怎么称呼你？' : 'Your name';
    if (message) message.placeholder = language === 'zh' ? '留下你的想法' : 'Leave a message';
    walk(document.body);
  }
  control.addEventListener('click', () => { language = language === 'zh' ? 'en' : 'zh'; localStorage.setItem('chasheo-language', language); apply(); });
  const observer = new MutationObserver(records => records.forEach(record => {
    if (record.type === 'characterData') translate(record.target as Text);
    else record.addedNodes.forEach(walk);
  }));
  observer.observe(document.body, { childList: true, characterData: true, subtree: true });
  apply();
}
